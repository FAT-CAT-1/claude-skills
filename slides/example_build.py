# -*- coding: utf-8 -*-
"""example_build.py — 雛形。これをコピーして中身を書き換える。

    python example_build.py            # 既定テーマで生成
    python example_build.py neon       # テーマを変えて生成

⚠この雛形は**部品の見本市**を兼ねている（全レシピを1枚ずつ使う）。
  実際の資料では、ここから要らない型を消して使う。
⚠生成しただけでは完成ではない。必ず:
    python verify.py example.pptx png   → 書き出した画像を1枚ずつ目で見る
"""
import sys
import os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from deck import Deck, note                                    # noqa: E402

THEME = sys.argv[1] if len(sys.argv) > 1 else 'lecture'
d = Deck(theme=THEME, ratio='16:9')

# ※ 以下の文面と数値はすべて架空の例（「みどり町 秋の朝市」の報告、という設定）。
#   実在の団体・催しとは関係ない。差し替えて使う。

# ── 型1: 看板（1枚に大きな1行）──────────────────────
d.board(
    '買って帰る、で\n終わっていた。',
    notes=note('0:00-0:20',
               'ここに実際に声に出す台詞を書く。\n（一拍おく）\n続きの台詞。',
               warn='自己紹介より先にこれを言う'))

d.board(
    'だから、*座れる市*を作った。',
    sub=['毎年同じ屋台が並び、30分で人がいなくなる。それが、あまりに惜しかった。'],
    notes=note('0:20-0:45', 'ここで画面を当日の写真に切り替える。'))

# ── 画面を見せる間は背景だけ（スライドを主役にしない）──
d.blank(notes=note('0:45-2:45',
                   '当日の写真を見せる。スライドは見せない。\n'
                   '見せる順: (1)…… (2)…… (3)……',
                   warn='写真が開かなければ「あとで配布します」と言って次へ。慌てない。'))

# ── 型2: 説明（見出し＋中身）────────────────────────
d.explain(
    'ここで何に躓いたか',
    ['告知が、町内の掲示板だけだった',
     '出店の顔ぶれが、10年ほど変わっていなかった',
     '思いついた企画を、*隣の町がすでにやっていた*'],
    caption='——この3つを、順に潰していった',
    notes=note('2:45-3:30', '箇条は読み上げない。指差して、1つずつ言葉で膨らませる。',
               warn='6個を超えたら看板ではなく資料になっている。分割する。'))

# ── レシピ1: 横棒グラフ ──────────────────────────
#   4列目に補足を書くと、ラベルの下に小さく出る
d.bars(
    '来場者アンケートで見えた*満足度*',
    [('食べ物の屋台', 72),
     ('雨の日の休める場所', 42, True, 'いちばん低かった項目'),
     ('子ども向けの企画', 72),
     ('会場の雰囲気', 89)],
    caption='※ 架空の数値。回答したのは来場者の一部だけ',
    notes=note('3:30-4:10', 'いちばん低かったのが、ここ。42パーセント。',
               warn='根拠を聞かれたら「回答したのは一部の方です」と即答する'))

# ── レシピ2: 左右の比較 ──────────────────────────
d.compare(
    'お客さんは、どこで過ごしていたか',
    left=('これまで', '買って *帰る*', '屋台で買って、そのまま帰る\n会場は ~通り道~'),
    right=('今回', '座って *過ごす*', '広場に椅子を並べ、話し込める\n*長くいられる場所*'),
    caption='屋台を12店から20店に増やし、真ん中に広場を作った',
    notes=note('4:10-4:40', 'どちらの列が何なのかを、必ず口でも言う。'))

# ── レシピ3: 2列の表 ────────────────────────────
d.table(
    '役割を分けた',
    [('実行委員会', 'すべての最終決定', True),
     ('商店会', '出店者の募集・調整'),
     ('学生ボランティア', '設営・案内'),
     ('町内会', 'ごみの回収')],
    caption='意見が割れたら案を並べ、最後は委員会が決める',
    notes=note('4:40-5:20', '「委員会が全部やった」でも「任せきりだった」でもない、が正確な言い方。'))

# ── レシピ4: 手順・変化 ──────────────────────────
d.steps(
    'たどった道',
    ['話を聞く', '行き止まる', '会場の形を変える', '人が残った'],
    caption='行き止まりを一つずつ潰した回数だった',
    notes=note('5:20-5:50', '矢印の最後で一拍おく。'))

# ── レシピ5: 数字を並べる ────────────────────────
d.numbers(
    'この3ヶ月でやったこと',
    [('12回', '実行委員会で話し合った'),
     ('約300人', 'アンケートに答えてもらった', 'fg'),
     ('20店', '屋台を出してもらった', 'a3'),
     ('40人以上', 'ボランティアが手伝ってくれた', 'a2')],
    caption='※ 数字は出典から機械的に取る。手で書いた数字は必ず腐る',
    notes=note('5:50-6:20', '数字は「大きさ」より「意味」で言う。'))

# ── 尺違いを1ファイルでまかなう ──────────────────
#   note(skip=[...]) を書いた枚は、その版では飛ばす。save() が一覧を出す。
d.board(
    'ここは短い版では飛ばす枚の例',
    notes=note('6:20-6:40', '短い版ではこの話を落とす。', skip=['5分版']))

# ── 締め ────────────────────────────────────────
d.board('決め台詞を、ここに。', size=52,
        notes=note('6:40-7:00', '言い終えたら黙る。拍手より先に喋らない。'))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'example.pptx')
d.save(out)
